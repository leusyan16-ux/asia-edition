import test from 'node:test';
import assert from 'node:assert/strict';
import {bookingEmail,bookingMailto,bookingTelegramUrl,bookingTelegramDraft} from '../src/features/inquiries/booking-contact';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {BookingContactForm} from '../src/features/inquiries/booking-contact-form';
test('booking request email: explicit draft only, input validation and encoded content',()=>{
 const input={name:'Тест',date:'2026-11-01',adults:2,children:1,message:'Test & body',consent:true};
 const product={title:'Test & activity',slug:'getyourguide-123'};
 const url=bookingMailto('office@example.com',product,input,'en','2026-10-26');
 assert(url.startsWith('mailto:office@example.com?subject='));assert(url.includes(encodeURIComponent('not a confirmed booking')));
 const parsed=new URL(url);assert(parsed.searchParams.get('body')?.includes('Test & body'));
 assert.equal(bookingEmail(undefined),null);assert.equal(bookingEmail('office@example.com?bcc=other@example.com'),null);
 assert.throws(()=>bookingMailto('office@example.com',product,{...input,consent:false},'en'));
 assert.throws(()=>bookingMailto('office@example.com',product,{...input,adults:30,children:1},'en'));
 assert.throws(()=>bookingMailto('office@example.com',product,{...input,date:'2020-01-01'},'en'));
 assert.throws(()=>bookingMailto('bad\r\n@example.com',product,input,'en'));
 const telegram=bookingTelegramDraft('https://t.me/TestTravel_bot',product,input,'en','2026-10-26');
 assert.equal(new URL(telegram.url).searchParams.get('start'),product.slug);
 assert(!telegram.url.includes(input.name)&&!telegram.url.includes(input.date));
 assert(telegram.text.includes('not a confirmed booking'));
 assert.equal(bookingTelegramUrl('https://evil.example/TestTravel_bot'),null);
 assert.equal(bookingTelegramUrl('https://t.me/TestTravel_bot?chat_id=12345'),null);
 assert.equal(bookingTelegramUrl('https://user:password@t.me/TestTravel_bot'),null);
 assert.throws(()=>bookingTelegramDraft('https://t.me/TestTravel_bot',product,{...input,consent:false},'en'));
 const html=renderToStaticMarkup(React.createElement(BookingContactForm,{telegramUrl:'https://t.me/TestTravel_bot',product,locale:'en'}));
 assert(html.includes('Prepare request'));assert(html.includes('does not save the request'));
 assert(!html.includes('Booking confirmed'));assert(!html.includes('chat_id'));
});
